//! The typescript-language-server spec: everything that is this server's and
//! not the generic client's, as the [`LanguageServerSpec`] the plugin's
//! `Language` carries.
//!
//! * discovery and launch (`locate.rs`): the setting, the project's
//!   `node_modules`, `PATH`, the approved managed install (`install.rs`), run
//!   through Node's entry point rather than the `.cmd` shim;
//! * the workspace (`prepare_workspace`): a `tsconfig.json` for the class
//!   folder that points at the generated `Pulsar/types/pulsar.d.ts`, with the
//!   DOM libraries off, so the class files see the script natives and not
//!   `window`;
//! * roots: the class folder (`src/classes`, where that tsconfig lives), else
//!   the nearest `tsconfig.json`;
//! * readiness: the server reports `Initializing JS/TS language features` as
//!   work-done progress; it is ready when that work has ended.

use std::path::{Path, PathBuf};
use std::time::Duration;

use pulsar_language::spec::{
    section_of, LanguageServerSpec, LocateContext, LocateError, ProgressEvent, ProgressKind,
    ProgressText, ReadinessRule, RootStrategy, ServerCommand, ServerContext, ServerHooks,
};
use serde_json::{json, Value};

use crate::{install, locate};

/// The spec's id: status, log, settings and diagnostics name it.
pub const ID: &str = "typescript-language-server";

/// The work-done progress title the server reports while it loads the project.
const INITIALIZING: &str = "Initializing JS/TS language features";

/// First line of a tsconfig this plugin wrote: it is rewritten while the line
/// is there, and left alone once the person removes it (their file now).
pub(crate) const GENERATED_MARKER: &str = "// Generated by Pulsar (pulsar.typescript)";

pub static SPEC: LanguageServerSpec = LanguageServerSpec {
    id: ID,
    display_name: "TypeScript language server",
    find,
    locate: locate_server,
    roots: RootStrategy::Custom(root_of),
    initialization_options,
    configuration,
    client_capabilities: || Value::Null,
    hooks: ServerHooks {
        progress,
        notification: |_, _| None,
        quick_fixes: |_, _| Vec::new(),
    },
    // Ready when the project has loaded: the server's own work-done progress.
    readiness: ReadinessRule::AllProgressEnded,
    // A server that never reports its initial work (an older one) is declared
    // ready after this, with a warning in its log.
    max_indexing: Duration::from_secs(45),
    eager: false,
    commands: &[],
    prepare_workspace: Some(prepare_workspace),
    installer: Some(&install::INSTALLER),
};

/// The server if it is there and can run, without installing anything.
fn find(ctx: &LocateContext) -> Option<ServerCommand> {
    locate::locate_here(ctx.project_root, ctx.configured_path.as_deref())
        .ok()
        .map(|located| located.command)
}

fn locate_server(ctx: &LocateContext) -> Result<ServerCommand, LocateError> {
    ctx.report("Looking for the TypeScript language server...");
    let located = locate::locate_here(ctx.project_root, ctx.configured_path.as_deref())?;
    tracing::info!(
        "typescript-language-server from {:?}{}",
        located.source,
        if located.via_shim {
            " (through its shim: no Node entry point was found beside it)"
        } else {
            ""
        }
    );
    Ok(located.command)
}

/// The class folder is one server's root (it holds the tsconfig this plugin
/// writes); any other file belongs to the nearest tsconfig, else the project.
fn root_of(file: &Path, project_root: &Path) -> Option<PathBuf> {
    let classes = classes_dir(project_root);
    if file.starts_with(&classes) {
        return Some(classes);
    }
    RootStrategy::NearestMarker(&["tsconfig.json", "jsconfig.json"]).root_for(file, project_root)
}

pub(crate) fn classes_dir(project_root: &Path) -> PathBuf {
    project_root.join("src").join("classes")
}

fn initialization_options(_: &ServerContext) -> Value {
    json!({
        "hostInfo": "Pulsar",
        // No network behind the person's back: no automatic @types downloads.
        "disableAutomaticTypingAcquisition": true,
        "preferences": {
            "includeCompletionsForModuleExports": true,
            "includeCompletionsWithInsertText": true,
            "includeCompletionsForImportStatements": true,
            "includeAutomaticOptionalChainCompletions": true,
        },
        "tsserver": { "logVerbosity": "off" },
    })
}

/// The server asks for the `typescript` and `javascript` sections; they are
/// looked up in the options' own objects, the rest is nothing.
fn configuration(context: &ServerContext, section: &str) -> Value {
    section_of(&SPEC.effective_initialization_options(context), section)
}

/// The server's loading work reads as one status line.
fn progress(event: &ProgressEvent) -> Option<ProgressText> {
    if event.kind == ProgressKind::Begin && event.title == INITIALIZING {
        return Some(ProgressText {
            text: "Loading the TypeScript project...".to_string(),
            fraction: None,
        });
    }
    (ServerHooks::DEFAULT.progress)(event)
}

/// The tsconfig of the class folder: classes are ambient (no imports), the
/// natives come from the generated declarations, and the DOM is off so
/// `window` and the browser's names do not shadow the script natives.
pub(crate) fn tsconfig_text() -> String {
    [
        GENERATED_MARKER,
        "// for the classes in this folder: the script natives come from",
        "// Pulsar/types/pulsar.d.ts, and the DOM libraries are off. It is rewritten",
        "// while the first line is here; delete that line to make this file yours.",
        "{",
        "  \"compilerOptions\": {",
        "    \"target\": \"ES2022\",",
        "    \"lib\": [\"ES2022\"],",
        "    \"types\": [],",
        "    \"strict\": true,",
        "    \"noEmit\": true,",
        "    \"skipLibCheck\": true,",
        "    \"moduleDetection\": \"legacy\"",
        "  },",
        "  \"include\": [\"**/class.ts\", \"../../Pulsar/types/*.d.ts\"]",
        "}",
        "",
    ]
    .join("\n")
}

/// Write the class folder's tsconfig and the declarations it points at before
/// the server starts, so the first file opened already sees the natives (they
/// used to appear only after the first compile). A tsconfig the person took
/// over (no marker line) is never touched.
fn prepare_workspace(context: &ServerContext) -> Result<(), String> {
    use engine_fs::virtual_fs as vfs;
    if context.root != classes_dir(&context.project_root) {
        return Ok(());
    }
    let natives = plugin_editor_api::NativeRegistry::with_engine_natives();
    crate::compile::write_declarations(&context.project_root, &natives);

    let path = context.root.join("tsconfig.json");
    let wanted = tsconfig_text();
    match vfs::read_to_string(&path) {
        Ok(existing) if !existing.starts_with(GENERATED_MARKER) => return Ok(()),
        Ok(existing) if existing == wanted => return Ok(()),
        _ => {}
    }
    vfs::write_file(&path, wanted.as_bytes())
        .map_err(|e| format!("could not write {}: {e}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use pulsar_language::settings::ServerSettings;

    fn context(project: &Path, root: &Path) -> ServerContext {
        ServerContext {
            root: root.to_path_buf(),
            project_root: project.to_path_buf(),
            settings: ServerSettings::default(),
        }
    }

    #[test]
    fn class_files_belong_to_the_class_folder_and_others_to_their_tsconfig() {
        let project = tempfile::tempdir().unwrap();
        let p = project.path();
        let class = p.join("src/classes/Door/class.ts");
        assert_eq!(root_of(&class, p), Some(p.join("src/classes")));

        let tool = p.join("tools/build/script.ts");
        std::fs::create_dir_all(tool.parent().unwrap()).unwrap();
        assert_eq!(
            root_of(&tool, p),
            Some(p.to_path_buf()),
            "no tsconfig: the project"
        );
        std::fs::write(p.join("tools/tsconfig.json"), "{}").unwrap();
        assert_eq!(
            root_of(&tool, p),
            Some(p.join("tools")),
            "the nearest tsconfig"
        );
    }

    #[test]
    fn the_tsconfig_points_at_the_declarations_with_the_dom_off() {
        let text = tsconfig_text();
        assert!(text.starts_with(GENERATED_MARKER));
        // Valid JSONC: strip the comment lines and parse.
        let json: Value = serde_json::from_str(
            &text
                .lines()
                .filter(|l| !l.trim_start().starts_with("//"))
                .collect::<Vec<_>>()
                .join("\n"),
        )
        .unwrap();
        assert_eq!(json["compilerOptions"]["lib"], json!(["ES2022"]), "no DOM");
        assert_eq!(json["compilerOptions"]["types"], json!([]));
        assert_eq!(json["compilerOptions"]["noEmit"], true);
        let include = json["include"].as_array().unwrap();
        assert!(include.iter().any(|i| i == "../../Pulsar/types/*.d.ts"));
        assert!(include.iter().any(|i| i == "**/class.ts"));
    }

    #[test]
    fn preparing_writes_the_tsconfig_and_the_declarations_and_respects_a_users_tsconfig() {
        let project = tempfile::tempdir().unwrap();
        let p = project.path();
        let classes = classes_dir(p);
        std::fs::create_dir_all(classes.join("Door")).unwrap();
        prepare_workspace(&context(p, &classes)).unwrap();
        assert_eq!(
            std::fs::read_to_string(classes.join("tsconfig.json")).unwrap(),
            tsconfig_text()
        );
        let declarations = std::fs::read_to_string(p.join("Pulsar/types/pulsar.d.ts")).unwrap();
        assert!(
            declarations.contains("ScriptClass"),
            "the d.ts exists before the first compile"
        );

        // A person who removed the marker line owns the file.
        std::fs::write(classes.join("tsconfig.json"), "{ \"mine\": true }").unwrap();
        prepare_workspace(&context(p, &classes)).unwrap();
        assert_eq!(
            std::fs::read_to_string(classes.join("tsconfig.json")).unwrap(),
            "{ \"mine\": true }"
        );

        // Another root (a user's own tsconfig directory) is not ours to prepare.
        let other = p.join("tools");
        std::fs::create_dir_all(&other).unwrap();
        prepare_workspace(&context(p, &other)).unwrap();
        assert!(!other.join("tsconfig.json").exists());
    }

    #[test]
    fn the_loading_work_reads_as_one_status_line_and_other_work_keeps_its_title() {
        let begin = |title| ProgressEvent {
            token: "t",
            kind: ProgressKind::Begin,
            title,
            message: None,
            percentage: None,
        };
        assert_eq!(
            progress(&begin(INITIALIZING)).unwrap().text,
            "Loading the TypeScript project..."
        );
        assert_eq!(
            progress(&begin("Finding references")).unwrap().text,
            "Finding references"
        );
    }

    #[test]
    fn it_is_ready_when_its_initial_work_has_ended_and_starts_on_the_first_file() {
        assert_eq!(SPEC.readiness, ReadinessRule::AllProgressEnded);
        assert!(!SPEC.eager);
        assert_eq!(SPEC.id, ID);
        assert!(SPEC.installer.is_some(), "the footer offers the install");
    }

    #[test]
    fn options_disable_typing_acquisition_and_the_persons_overlay_wins() {
        let mut ctx = context(Path::new("/p"), Path::new("/p/src/classes"));
        let options = SPEC.effective_initialization_options(&ctx);
        assert_eq!(options["disableAutomaticTypingAcquisition"], true);
        ctx.settings.initialization_options =
            Some(json!({ "tsserver": { "logVerbosity": "verbose" } }));
        let options = SPEC.effective_initialization_options(&ctx);
        assert_eq!(options["tsserver"]["logVerbosity"], "verbose");
        assert_eq!(options["hostInfo"], "Pulsar", "the rest is untouched");
        assert_eq!(
            configuration(&ctx, "tsserver.logVerbosity"),
            json!("verbose")
        );
        assert_eq!(configuration(&ctx, "nothing"), Value::Null);
    }
}
